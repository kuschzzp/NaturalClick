export const DEFAULT_LOCALE: SidepanelLocale = "en";

export function normalizeLocale(value: unknown): SidepanelLocale {
  return value === "zh-CN" ? "zh-CN" : DEFAULT_LOCALE;
}

export function createTranslator(locale: unknown = DEFAULT_LOCALE): (key: TranslationKey, params?: Record<string, string | number>) => string {
  const table = normalizeLocale(locale) === "zh-CN" ? zh : en;
  return (key, params = {}) => {
    let value: string = table[key] ?? en[key] ?? key;
    Object.entries(params).forEach(([name, replacement]) => {
      value = value.replaceAll(`{${name}}`, String(replacement));
    });
    return value;
  };
}
